// buildFieldMappings 共用物理字段构造；创建索引要求完整精度，查询能力描述兼容历史未保存的精度。
func buildFieldMappings(schemaDefinition []*interfaces.Property, requireComplete bool) (map[string]any, error) {
	properties := map[string]any{}
	declaredFields := make(map[string]struct{}, len(schemaDefinition))
	for _, prop := range schemaDefinition {
		declaredFields[prop.Name] = struct{}{}
	}

	for _, prop := range schemaDefinition {
		if prop.Type == interfaces.DataType_Other {
			return nil, fmt.Errorf("unsupported schema field %q: type %s (original_type: %s)", prop.Name, prop.Type, prop.OriginalType)
		}
		fieldType := fieldMappingType(prop.Type)

		fieldProps := map[string]any{"type": fieldType}
		var decimalConfig *interfaces.DecimalIndexConfig
		if prop.Type == interfaces.DataType_Decimal {
			config, err := DecimalIndexConfig(prop, interfaces.TableColumnMeta{})
			if err != nil {
				return nil, err
			}
			if requireComplete || config.Precision > 0 || decimalTypePattern.MatchString(prop.OriginalType) {
				if err := ValidateDecimalIndexConfig(prop.Name, config); err != nil {
					return nil, err
				}
			}
			if config.Precision > 0 {
				decimalConfig = config
				if config.Scale <= 0 {
					fieldType = "long"
					fieldProps["type"] = fieldType
					fieldProps["coerce"] = false
				} else {
					fieldProps["scaling_factor"] = math.Pow10(config.Scale)
				}
			}
		}

		if prop.Type == interfaces.DataType_Json {
			// 仅透传 schema 中显式记录的策略，历史字段缺省时不补写 enabled。
			if enabled, exists := prop.Attributes["enabled"]; exists {
				fieldProps["enabled"] = enabled
			}
			properties[prop.Name] = fieldProps
			continue
		}

		for _, feature := range prop.Features {
			if feature.FeatureType == interfaces.PropertyFeatureType_Fulltext {
				applyFulltextFeature(fieldProps, prop, feature)
				continue
			}
			switch feature.FeatureType {
			case interfaces.PropertyFeatureType_Keyword:
				applyKeywordFeature(fieldProps, prop, feature)
			case interfaces.PropertyFeatureType_Vector:
				if feature.Config != nil && prop.Type == interfaces.DataType_Vector {
					if dimension, exists := feature.Config["dimension"]; exists {
						fieldProps["dimension"] = dimension
					}
				}
			default:
				if feature.Config != nil {
					return nil, fmt.Errorf("unsupported feature type: %s", feature.FeatureType)
				}
			}
		}

		if prop.Type == interfaces.DataType_Vector {
			fieldProps["method"] = defaultVectorMethod()
		}
		if decimalConfig != nil {
			// Feature 配置不能覆盖数值编码或跳过非法数值，否则会重新引入静默损坏。
			invalidEncoding := fieldProps["type"] != "scaled_float" || fieldProps["scaling_factor"] != math.Pow10(decimalConfig.Scale)
			if decimalConfig.Scale <= 0 {
				_, hasScalingFactor := fieldProps["scaling_factor"]
				invalidEncoding = fieldProps["type"] != "long" || hasScalingFactor || fieldProps["coerce"] != false
			}
			if invalidEncoding ||
				fieldProps["ignore_malformed"] == true || fieldProps["null_value"] != nil {
				return nil, interfaces.NewDecimalIndexError(prop.Name, "unsafe_mapping_override")
			}
		}
		properties[prop.Name] = fieldProps
	}

	for _, prop := range schemaDefinition {
		if prop.Type != interfaces.DataType_String && prop.Type != interfaces.DataType_Text {
			continue
		}
		for _, feature := range prop.Features {
			if feature.FeatureType != interfaces.PropertyFeatureType_Vector || feature.RefProperty != "" {
				continue
			}
			generatedName := VectorFieldName(prop.Name)
			if _, exists := declaredFields[generatedName]; exists {
				return nil, fmt.Errorf("generated vector field %q conflicts with declared field", generatedName)
			}
			dimension, ok := feature.Config["dimension"]
			if !ok {
				return nil, fmt.Errorf("vector feature for field %q has no resolved dimension", prop.Name)
			}
			fieldMapping := map[string]any{
				"type":      "knn_vector",
				"dimension": dimension,
			}
			for key, value := range feature.Config {
				if key != "embedding_model" && key != "method" {
					fieldMapping[key] = value
				}
			}
			fieldMapping["method"] = defaultVectorMethod()
			properties[generatedName] = fieldMapping
		}
	}

	return properties, nil
}

// VectorFieldName returns the physical vector field generated by the active local index manager.
func VectorFieldName(field string) string {
	return field + interfaces.LocalIndexVectorFieldSuffix
}

func applyFulltextFeature(fieldProps map[string]any, property *interfaces.Property, feature interfaces.PropertyFeature) {
	switch property.Type {
	case interfaces.DataType_String:
		fieldName := strings.TrimSpace(feature.FeatureName)
		if fieldName == "" {
			fieldName = interfaces.LocalIndexFulltextSubfieldName
		} else {
			fieldName = strings.TrimPrefix(fieldName, property.Name+".")
		}
		subfield := map[string]any{"type": "text"}
		for key, value := range feature.Config {
			subfield[key] = value
		}
		fields, ok := fieldProps["fields"].(map[string]any)
		if !ok {
			fields = map[string]any{}
			fieldProps["fields"] = fields
		}
		fields[fieldName] = subfield
	case interfaces.DataType_Text:
		for key, value := range feature.Config {
			fieldProps[key] = value
		}
	}
}

func applyKeywordFeature(fieldProps map[string]any, property *interfaces.Property, feature interfaces.PropertyFeature) {
	if property.Type != interfaces.DataType_Text {
		for key, value := range feature.Config {
			fieldProps[key] = value
		}
		return
	}
	fieldName := strings.TrimSpace(feature.FeatureName)
	if fieldName == "" {
		fieldName = interfaces.LocalIndexKeywordSubfieldName
	} else {
		fieldName = strings.TrimPrefix(fieldName, property.Name+".")
	}
	fields, ok := fieldProps["fields"].(map[string]any)
	if !ok {
		fields = map[string]any{}
		fieldProps["fields"] = fields
	}
	subfield := map[string]any{"type": "keyword"}
	for key, value := range feature.Config {
		subfield[key] = value
	}
	fields[fieldName] = subfield
}

func defaultVectorMethod() map[string]any {
	return map[string]any{
		"name":       "hnsw",
		"engine":     "lucene",
		"parameters": map[string]any{"ef_construction": 256},
	}
}

// fieldMappingType 与创建索引共用逻辑类型到物理映射类型的转换。
func fieldMappingType(dataType string) string {
	switch dataType {
	case interfaces.DataType_Integer:
		return "long"
	case interfaces.DataType_UnsignedInteger:
		return "unsigned_long"
	case interfaces.DataType_Float:
		return "double"
	case interfaces.DataType_Decimal:
		return "scaled_float"
	case interfaces.DataType_String, interfaces.DataType_LargeInteger, interfaces.DataType_Time:
		return "keyword"
	case interfaces.DataType_Datetime, interfaces.DataType_Timestamp:
		return "date"
	case interfaces.DataType_Json:
		return "object"
	case interfaces.DataType_Vector:
		return "knn_vector"
	case interfaces.DataType_Point:
		return "geo_point"
	case interfaces.DataType_Shape:
		return "geo_shape"
	default:
		return dataType
	}
}

// queryFieldMappings 复用创建索引的最终 mapping，不继承源字段的索引开关。
func queryFieldMappings(schema []*interfaces.Property) (map[string]any, error) {
	properties := make([]*interfaces.Property, 0, len(schema))
	for _, property := range schema {
		if isQueryableFieldType(property.Type) {
			properties = append(properties, property)
		}
	}
	return buildFieldMappings(properties, false)
}

// indexFieldMeta 将最终物理 mapping 转为连接器使用的字段元数据。
func indexFieldMeta(name string, mapping map[string]any) *interfaces.IndexFieldMeta {
	meta := &interfaces.IndexFieldMeta{Name: name, Attributes: make(map[string]any)}
	meta.Type, _ = mapping["type"].(string)
	for key, value := range mapping {
		if key != "type" && key != "fields" && key != "properties" {
			meta.Attributes[key] = value
		}
	}
	fields, _ := mapping["fields"].(map[string]any)
	names := make([]string, 0, len(fields))
	for fieldName := range fields {
		names = append(names, fieldName)
	}
	sort.Strings(names)
	for _, fieldName := range names {
		fieldMapping, _ := fields[fieldName].(map[string]any)
		subfield := indexFieldMeta(fieldName, fieldMapping)
		meta.SubFields = append(meta.SubFields, interfaces.IndexSubFieldMeta{
			Name:       subfield.Name,
			Type:       subfield.Type,
			Attributes: subfield.Attributes,
		})
	}
	return meta
}
