#!/usr/bin/env python3
"""Verify OpenBKN license markers in BKN Trace authored source and config files."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
TRACE_ROOT = Path("bkn-trace")
REQUIRED_MARKERS = (
    "Copyright (c) 2026 OpenBKN",
    "SPDX-License-Identifier: LicenseRef-OpenBKN",
    "Licensed under the OpenBKN License",
)
COMMENTABLE_SUFFIXES = {
    ".go",
    ".py",
    ".sh",
    ".sql",
    ".toml",
    ".tpl",
    ".yaml",
    ".yml",
}
COMMENTABLE_NAMES = {"Dockerfile", "Makefile"}
EXCLUDED_FILES = {
    # Generated by Swagger tooling; modify its generator instead of this output.
    Path("bkn-trace/agent-observability/docs/swagger/docs.go"),
}


def is_commentable(path: Path) -> bool:
    # Applied migrations are checksum-protected deployment artifacts. A comment
    # would mutate their schema bytes and invalidate the durable ledger.
    if path.match("bkn-trace/agent-observability/migrations/mariadb/*/init.sql"):
        return False
    return path.name in COMMENTABLE_NAMES or path.suffix in COMMENTABLE_SUFFIXES


def validate_content(path: Path, content: str) -> list[str]:
    del path
    for marker in REQUIRED_MARKERS:
        if marker not in content:
            return [f"missing {marker}"]
    return []


def tracked_trace_files() -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "bkn-trace"],
        cwd=ROOT,
        capture_output=True,
        check=True,
        text=True,
    )
    return [Path(line) for line in result.stdout.splitlines()]


def main() -> int:
    failures: list[str] = []
    for path in tracked_trace_files():
        if path in EXCLUDED_FILES or not is_commentable(path):
            continue
        errors = validate_content(path, (ROOT / path).read_text(encoding="utf-8"))
        failures.extend(f"{path}: {error}" for error in errors)

    if failures:
        print("BKN Trace files missing required OpenBKN license markers:", file=sys.stderr)
        print("\n".join(f"- {failure}" for failure in failures), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
