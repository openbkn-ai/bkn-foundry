// The custom methods on a project's concepts, under POST /projects/{project_id}/ontology/:action.
const (
	conceptsActionJudge = "concepts:judge"
	conceptsActionMerge = "concepts:merge"
)

func (r *restHandler) GetConceptsByEx(c *gin.Context) { r.withExVisitor(c, r.GetConcepts) }

// GetConcepts replies the project's concepts.
func (r *restHandler) GetConcepts(c *gin.Context, visitor hydra.Visitor) {
	ctx, span := oteltrace.StartServerSpan(c)
	defer span.End()
	oteltrace.AddHttpAttrs4API(span, oteltrace.GetAttrsByGinCtx(c))

	id := c.Param("project_id")
	span.SetAttributes(attr.Key("project_id").String(id))

	concepts, err := r.drs.GetConcepts(ctx, visitor.TokenID, id)
	if err != nil {
		replyError(c, span, err)
		return
	}
	oteltrace.AddHttpAttrs4Ok(span, http.StatusOK)
	rest.ReplyOK(c, http.StatusOK, concepts)
}

// JudgeConcept records what a concept is and replies the concepts.
func (r *restHandler) JudgeConcept(c *gin.Context, visitor hydra.Visitor) {
	ctx, span := oteltrace.StartServerSpan(c)
	defer span.End()
	oteltrace.AddHttpAttrs4API(span, oteltrace.GetAttrsByGinCtx(c))

	id := c.Param("project_id")
	span.SetAttributes(attr.Key("project_id").String(id))

	var req interfaces.DraftConceptJudge
	if err := c.ShouldBindJSON(&req); err != nil {
		replyError(c, span, httperrors.NewHTTPError(ctx, http.StatusBadRequest, perrors.BknProject_Draft_InvalidRequestBody))
		return
	}
	concepts, err := r.drs.JudgeConcept(ctx, visitor.TokenID, id, req, visitorAccount(visitor))
	if err != nil {
		replyError(c, span, err)
		return
	}
	oteltrace.AddHttpAttrs4Ok(span, http.StatusOK)
	rest.ReplyOK(c, http.StatusOK, concepts)
}

